  const hasOwn = (object, key) => Object.prototype.hasOwnProperty.call(object, key);

  function normalizeLanguage(value) {
    if (preferenceApi?.normalizeLanguage) return preferenceApi.normalizeLanguage(value);
    const normalized = String(value || "").trim().toLowerCase();
    if (normalized.startsWith("ru")) return "ru";
    if (normalized.startsWith("en")) return "en";
    return null;
  }

  function normalizeTheme(value) {
    if (preferenceApi?.normalizeTheme) return preferenceApi.normalizeTheme(value);
    return ["system", "light", "dark"].includes(value) ? value : null;
  }

  function safeStorage(store) {
    return store && typeof store.getItem === "function" && typeof store.setItem === "function" ? store : null;
  }

  function readPresentationPreferences(store) {
    if (preferenceApi?.read) return preferenceApi.read(store);
    const storage = safeStorage(store);
    const preferences = { version: PREFERENCE_VERSION, language: null, theme: "system", density: "comfortable" };
    if (!storage) return preferences;
    let raw = null;
    try {
      raw = storage.getItem(PREFERENCES_STORAGE_KEY);
    } catch (_error) {
      return preferences;
    }
    if (raw !== null && raw !== "") {
      try {
        const parsed = JSON.parse(raw);
        if (!parsed || typeof parsed !== "object" || parsed.version !== PREFERENCE_VERSION) return preferences;
        preferences.language = normalizeLanguage(parsed.language);
        preferences.theme = normalizeTheme(parsed.theme) || "system";
        preferences.density = DENSITIES.has(parsed.density) ? parsed.density : "comfortable";
        return preferences;
      } catch (_error) {
        return preferences;
      }
    }
    try {
      preferences.language = normalizeLanguage(storage.getItem(STORAGE_KEY));
      preferences.theme = normalizeTheme(storage.getItem(LEGACY_THEME_STORAGE_KEY)) || "system";
    } catch (_error) {
      // Legacy storage is optional and never blocks rendering.
    }
    return preferences;
  }

  function writePresentationPreferences(store, updates = {}) {
    if (preferenceApi?.write) return preferenceApi.write(store, updates);
    const storage = safeStorage(store);
    const current = readPresentationPreferences(storage);
    const next = {
      version: PREFERENCE_VERSION,
      language: normalizeLanguage(updates.language) || current.language || "en",
      theme: normalizeTheme(updates.theme) || current.theme || "system",
      density: DENSITIES.has(updates.density) ? updates.density : current.density,
    };
    if (!storage) return next;
    try {
      storage.setItem(PREFERENCES_STORAGE_KEY, JSON.stringify(next));
    } catch (_error) {
      // Storage is a convenience, never presentation authority.
    }
    return next;
  }

  function interpolate(value, variables) {
    return value.replace(/\{\{(\w+)\}\}/g, (_match, key) => (
      hasOwn(variables, key) ? String(variables[key]) : ""
    ));
  }

  function pluralCategory(language, count) {
    if (typeof count !== "number" || !Number.isFinite(count)) return "unknown";
    const numeric = count;
    if (numeric === 0) return "zero";
    try {
      return new Intl.PluralRules(language).select(numeric);
    } catch (_error) {
      return numeric === 1 ? "one" : "other";
    }
  }

  function createI18n(options = {}) {
    let browserStorage = null;
    if (!hasOwn(options, "storage")) {
      try {
        browserStorage = root.localStorage;
      } catch (_error) {
        browserStorage = null;
      }
    }
    const storage = hasOwn(options, "storage") ? options.storage : browserStorage;
    const locale = options.locale || root.navigator?.language || root.navigator?.languages?.[0] || "en";
    const preferences = readPresentationPreferences(storage);
    let language = preferences.language || normalizeLanguage(locale) || "en";
    const listeners = new Set();

    function writeStored(value) {
      writePresentationPreferences(storage, { language: value });
      // Keep the legacy key readable for older embedded shells while the v1
      // record remains the only source for new preference fields.
      if (!storage || typeof storage.setItem !== "function") return;
      try { storage.setItem(STORAGE_KEY, value); } catch (_error) { /* optional */ }
    }

    function lookup(key) {
      if (hasOwn(translations[language], key)) return translations[language][key];
      if (hasOwn(translations.en, key)) return translations.en[key];
      return undefined;
    }

    function t(key, variables = {}) {
      const value = lookup(key);
      return interpolate(value === undefined ? key : value, variables);
    }

    function plural(key, count, variables = {}) {
      const category = pluralCategory(language, count);
      const selected = lookup(`${key}.${category}`) || lookup(`${key}.other`) || lookup(key);
      return interpolate(selected === undefined ? key : selected, { ...variables, count });
    }

    function status(value) {
      const canonical = value == null || value === "" ? "unknown" : String(value);
      const statusKey = canonical.toLowerCase().replaceAll(" ", "_").replaceAll("-", "_");
      const translated = lookup(`status.${statusKey}`);
      return translated === undefined ? canonical : translated;
    }

    return {
      get language() {
        return language;
      },
      dictionaries: translations,
      t,
      plural,
      status,
      setLanguage(nextLanguage) {
        const next = normalizeLanguage(nextLanguage);
        if (!next) return language;
        language = next;
        writeStored(language);
        for (const listener of listeners) listener(language);
        return language;
      },
      subscribe(listener) {
        listeners.add(listener);
        return () => listeners.delete(listener);
      }
    };
  }

  root.AoaDashboardI18n = {
    STORAGE_KEY,
    PREFERENCES_STORAGE_KEY,
    PREFERENCE_VERSION,
    pluralCategory,
    DENSITIES: Array.from(DENSITIES),
    dictionaries: translations,
    normalizeLanguage,
    normalizeTheme,
    readPresentationPreferences,
    writePresentationPreferences,
    createI18n
  };
