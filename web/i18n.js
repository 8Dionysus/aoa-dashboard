  const hasOwn = (object, key) => Object.prototype.hasOwnProperty.call(object, key);

  function normalizeLanguage(value) {
    const normalized = String(value || "").trim().toLowerCase();
    if (normalized.startsWith("ru")) return "ru";
    if (normalized.startsWith("en")) return "en";
    return null;
  }

  function interpolate(value, variables) {
    return value.replace(/\{\{(\w+)\}\}/g, (_match, key) => (
      hasOwn(variables, key) ? String(variables[key]) : ""
    ));
  }

  function createI18n(options = {}) {
    let browserStorage = null;
    if (!hasOwn(options, "storage")) {
      try {
        browserStorage = root.localStorage;
      } catch (_error) {
        browserStorage = null;
      }
    }
    const storage = hasOwn(options, "storage") ? options.storage : browserStorage;
    const locale = options.locale || root.navigator?.language || root.navigator?.languages?.[0] || "en";
    let language = normalizeLanguage(readStored(storage)) || normalizeLanguage(locale) || "en";
    const listeners = new Set();

    function readStored(store) {
      if (!store || typeof store.getItem !== "function") return null;
      try {
        return store.getItem(STORAGE_KEY);
      } catch (_error) {
        return null;
      }
    }

    function writeStored(value) {
      if (!storage || typeof storage.setItem !== "function") return;
      try {
        storage.setItem(STORAGE_KEY, value);
      } catch (_error) {
        // A storage failure must not prevent the presentation layer from switching.
      }
    }

    function lookup(key) {
      if (hasOwn(translations[language], key)) return translations[language][key];
      if (hasOwn(translations.en, key)) return translations.en[key];
      return undefined;
    }

    function t(key, variables = {}) {
      const value = lookup(key);
      return interpolate(value === undefined ? key : value, variables);
    }

    function status(value) {
      const canonical = value == null || value === "" ? "unknown" : String(value);
      const statusKey = canonical.toLowerCase().replaceAll(" ", "_").replaceAll("-", "_");
      const translated = lookup(`status.${statusKey}`);
      return translated === undefined ? canonical : translated;
    }

    return {
      get language() {
        return language;
      },
      dictionaries: translations,
      t,
      status,
      setLanguage(nextLanguage) {
        const next = normalizeLanguage(nextLanguage);
        if (!next) return language;
        language = next;
        writeStored(language);
        for (const listener of listeners) listener(language);
        return language;
      },
      subscribe(listener) {
        listeners.add(listener);
        return () => listeners.delete(listener);
      }
    };
  }

  root.AoaDashboardI18n = {
    STORAGE_KEY,
    dictionaries: translations,
    normalizeLanguage,
    createI18n
  };
